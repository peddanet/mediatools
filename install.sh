#!/usr/bin/env bash
# install.sh - create a "mediatools" launcher without pip.
#
# Usage:  ./install.sh            -> launcher in ~/scripts (must be in PATH)
#         BIN_DIR=~/bin ./install.sh
# Runs as normal user; it only writes one file into BIN_DIR.
set -euo pipefail

REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
BIN_DIR="${BIN_DIR:-$HOME/scripts}"
LAUNCHER="$BIN_DIR/mediatools"

python3 - <<'PY' || { echo "Python >= 3.10 required" >&2; exit 1; }
import sys; sys.exit(0 if sys.version_info >= (3, 10) else 1)
PY

mkdir -p "$BIN_DIR"
if [ -e "$LAUNCHER" ] && ! grep -q "mediatools launcher" "$LAUNCHER"; then
  echo "Refusing to overwrite foreign file: $LAUNCHER" >&2
  exit 1
fi
cat > "$LAUNCHER" <<SH
#!/bin/sh
# mediatools launcher (generated by $REPO/install.sh)
PYTHONPATH="$REPO/src\${PYTHONPATH:+:\$PYTHONPATH}" exec python3 -m mediatools "\$@"
SH
chmod 755 "$LAUNCHER"
echo "launcher: $LAUNCHER"

for tool in ffmpeg ffprobe rsync gio vlc; do
  command -v "$tool" >/dev/null 2>&1 && echo "  found:   $tool" || echo "  missing: $tool (optional, see README)"
done
case ":$PATH:" in
  *":$BIN_DIR:"*) "$LAUNCHER" --version ;;
  *) echo "NOTE: $BIN_DIR is not in PATH - add it in ~/.profile" ;;
esac
