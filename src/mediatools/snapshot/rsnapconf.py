"""Generation and test of the rsnapshot configuration file."""
from __future__ import annotations

import os
import shutil
import subprocess

from mediatools.core.datadir import DataDir
from mediatools.snapshot.settings import SnapshotSettings


class RsnapshotConf:
    """Writes ``<data root>/snapshot/rsnapshot.conf`` and calls rsnapshot.

    The file is generated from :class:`SnapshotSettings` on every run, so the
    INI file stays the single place to edit. Important fixed choices:

    * ``no_create_root 1`` - rsnapshot refuses to work if the snapshot root
      is missing, i.e. if the disk is not mounted (otherwise it would fill
      the empty mount point on the system disk).
    * ``sync_first 1`` - ``rsnapshot sync`` copies into ``.sync``; the level
      commands only rotate.
    * ``link_dest 1`` and ``-aH --no-inc-recursive`` - unchanged files and
      hard links (``_flat`` views) are shared, never duplicated.
    * ``--delete`` only affects ``.sync``; deleted files remain in older
      snapshots.

    Attributes:
        settings: Validated settings.
        path: Location of the generated file.
        log_file: rsnapshot's own log file.
        lock_file: rsnapshot's lock file (prevents parallel runs).
    """

    def __init__(self, settings: SnapshotSettings, datadir: DataDir | None = None):
        """Choose the file locations.

        Args:
            settings: Validated settings.
            datadir: Data directory; the default one if None.
        """
        self.settings = settings
        base = (datadir or DataDir()).sub("snapshot")
        self.path = os.path.join(base, "rsnapshot.conf")
        self.log_file = os.path.join(base, "rsnapshot.log")
        self.lock_file = os.path.join(base, "rsnapshot.pid")

    def render(self) -> str:
        """Build the configuration text (fields separated by tabs).

        Returns:
            Content of ``rsnapshot.conf``.

        Raises:
            SystemExit: If ``cp`` or ``rsync`` cannot be found.
        """
        tools = {name: shutil.which(name) for name in ("cp", "rsync")}
        missing = [name for name, path in tools.items() if path is None]
        if missing:
            raise SystemExit("Error: required tool(s) not found: " + ", ".join(missing))
        rows = [
            ("config_version", "1.2"),
            ("snapshot_root", self.settings.root.rstrip("/") + "/"),
            ("no_create_root", "1"),
            ("cmd_cp", str(tools["cp"])),
            ("cmd_rsync", str(tools["rsync"])),
            ("rsync_short_args", "-aH"),
            ("rsync_long_args", "--delete --numeric-ids --relative --delete-excluded "
                                "--no-inc-recursive"),
            ("link_dest", "1"),
            ("sync_first", "1"),
            ("verbose", "2"),
            ("loglevel", "3"),
            ("logfile", self.log_file),
            ("lockfile", self.lock_file),
        ]
        rows += [("retain", f"{level}\t{count}") for level, count in self.settings.retain]
        rows += [("exclude", pattern) for pattern in self.settings.exclude]
        rows.append(("backup", f"{self.settings.source.rstrip('/')}/\tlocalhost/"))
        return "# generated by mediatools - edit mediatools.ini instead\n" + \
            "".join(f"{key}\t{value}\n" for key, value in rows)

    def write(self) -> str:
        """Write the configuration file.

        Returns:
            Its path.
        """
        with open(self.path, "w", encoding="utf-8") as handle:
            handle.write(self.render())
        return self.path

    def command(self, *args: str) -> list[str]:
        """Build an rsnapshot command line for the generated file.

        Args:
            *args: rsnapshot arguments, e.g. ``"sync"``.

        Returns:
            Argument list.
        """
        return ["rsnapshot", "-c", self.path, *args]

    def configtest(self) -> tuple[bool, str]:
        """Run ``rsnapshot configtest``.

        Returns:
            ``(ok, output)``.
        """
        res = subprocess.run(self.command("configtest"), capture_output=True, text=True,
                             check=False)
        return res.returncode == 0, (res.stdout + res.stderr).strip()

    def run(self, *args: str) -> int:
        """Run rsnapshot with output on the terminal.

        Args:
            *args: rsnapshot arguments, e.g. ``"sync"`` or ``"alpha"``.

        Returns:
            Exit code (0 ok, 1 fatal error, 2 warnings).
        """
        return subprocess.run(self.command(*args), check=False).returncode
